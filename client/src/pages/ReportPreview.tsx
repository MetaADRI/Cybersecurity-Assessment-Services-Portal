import { Link, useParams } from 'react-router-dom';
import { Download } from 'lucide-react';
import { PageHeader } from '../components/Layout';
import { Button, Card, ErrorState, Notice, ScoreBar, Spinner, StatusBadge } from '../components/ui';
import { useApi } from '../hooks/useApi';
import { apiUrl } from '../lib/config';
import { formatDate, formatDateTime, label } from '../lib/format';
import type { ReportRecord } from '../../../shared/types';
import type { ReportBlock, ReportContent } from '../lib/reportTypes';

export default function ReportPreview() {
  const { id } = useParams();
  const { data, error, loading, refetch } = useApi<{
    report: ReportRecord;
    content: ReportContent | null;
  }>(id ? `/reports/${id}` : null);

  if (loading) return <Spinner label="Loading report" />;
  if (error) return <ErrorState message={error.message} onRetry={refetch} />;
  if (!data) return null;

  const { report, content } = data;

  return (
    <>
      <PageHeader
        title={report.title}
        subtitle={`${report.reportKey} - ${label(report.type)} - generated ${formatDateTime(report.generatedAt)}`}
        actions={
          report.status === 'generated' ? (
            <a href={apiUrl(`/reports/${report.id}/download`)}>
              <Button>
                <Download className="h-4 w-4" /> Download PDF
              </Button>
            </a>
          ) : undefined
        }
      />

      {report.status !== 'generated' && (
        <div className="mb-4">
          <Notice tone="danger">This report failed to generate: {report.errorMessage}</Notice>
        </div>
      )}

      <div className="mb-4 grid gap-4 sm:grid-cols-4">
        <Card title="Customer">
          <p className="text-sm text-slate-700">{report.customerName}</p>
        </Card>
        <Card title="Assessment">
          <p className="text-sm text-slate-700">{report.assessmentTitle ?? 'Not linked'}</p>
        </Card>
        <Card title="Generated by">
          <p className="text-sm text-slate-700">{report.generatedByName ?? 'System'}</p>
        </Card>
        <Card title="Snapshot">
          <p className="text-sm text-slate-700">
            {content ? 'Stored with the report' : 'No snapshot'} - {report.fileSize} bytes
          </p>
        </Card>
      </div>

      {!content && (
        <div className="mb-4">
          <Notice tone="warning">
            No stored content for this report. The PDF file can still be downloaded if it exists on
            disk.
          </Notice>
        </div>
      )}

      {content && (
        <div className="space-y-5">
          <Card
            title="Report contents"
            description="Exactly what the PDF contains - stored with the report"
          >
            <div className="mb-4 flex flex-wrap gap-2 text-xs">
              <span className="rounded border border-slate-200 bg-slate-50 px-2 py-1">
                {content.customer.name}
              </span>
              <span className="rounded border border-slate-200 bg-slate-50 px-2 py-1">
                {content.assessment.key} - {formatDate(content.assessment.date)}
              </span>
              <span className="rounded border border-slate-200 bg-slate-50 px-2 py-1">
                {content.assessment.fromSnapshot ? 'From frozen snapshot' : 'Live calculation'}
              </span>
              {content.score && (
                <span className="rounded border border-blue-200 bg-blue-50 px-2 py-1 text-blue-700">
                  Score {content.score.overallScore?.toFixed(1) ?? 'n/a'} - coverage{' '}
                  {content.score.coveragePct}%
                </span>
              )}
            </div>
            <div className="space-y-4">
              {content.blocks.map((block, i) => (
                <BlockView key={i} block={block} />
              ))}
            </div>
          </Card>

          <Card title="Limitations and exclusions">
            <ul className="list-disc space-y-1 pl-5 text-sm text-slate-600">
              {content.limitations.map((l) => (
                <li key={l}>{l}</li>
              ))}
            </ul>
          </Card>

          <p className="text-xs text-slate-500">
            <Link to={`/assessments/${report.assessmentId}`} className="text-blue-600 underline">
              Open the assessment
            </Link>{' '}
            - report status: <StatusBadge status={report.status} />
          </p>
        </div>
      )}
    </>
  );
}

function BlockView({ block }: { block: ReportBlock }) {
  switch (block.kind) {
    case 'heading':
      return (
        <h2
          className={
            block.level === 1
              ? 'text-xl font-bold text-slate-900'
              : block.level === 2
                ? 'border-l-3 border-blue-500 pl-3 text-lg font-semibold text-slate-900'
                : 'text-base font-semibold text-slate-700'
          }
        >
          {block.text}
        </h2>
      );
    case 'paragraph':
      return <p className="text-sm leading-relaxed text-slate-700">{block.text}</p>;
    case 'bullets':
      return (
        <ul className="list-disc space-y-1 pl-5 text-sm text-slate-700">
          {block.items.map((item, i) => (
            <li key={i}>{item}</li>
          ))}
        </ul>
      );
    case 'kv':
      return (
        <dl className="grid gap-x-6 gap-y-2 text-sm sm:grid-cols-2">
          {block.pairs.map(([k, v]) => (
            <div key={k} className="flex justify-between gap-3 border-b border-slate-100 pb-1">
              <dt className="text-slate-500">{k}</dt>
              <dd className="text-right font-medium text-slate-800">{v}</dd>
            </div>
          ))}
        </dl>
      );
    case 'table':
      return (
        <div className="overflow-x-auto">
          <table className="w-full border-collapse text-xs">
            <thead>
              <tr className="bg-navy-900 text-white">
                {block.headers.map((h) => (
                  <th
                    key={h}
                    className="border border-slate-300 px-2 py-1.5 text-left font-semibold"
                  >
                    {h}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {block.rows.map((row, i) => (
                <tr key={i} className={i % 2 === 1 ? 'bg-slate-50' : ''}>
                  {row.map((cell, j) => (
                    <td key={j} className="border border-slate-200 px-2 py-1.5 text-slate-700">
                      {cell}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      );
    case 'chart':
      return (
        <div>
          <p className="mb-2 text-sm font-semibold text-slate-900">{block.title}</p>
          <div className="space-y-1.5">
            {block.data.map((d) => (
              <ScoreBar key={d.label} label={d.label} value={d.value < 0 ? null : d.value} />
            ))}
          </div>
        </div>
      );
    case 'pagebreak':
      return <hr className="border-slate-200" />;
    default:
      return null;
  }
}
